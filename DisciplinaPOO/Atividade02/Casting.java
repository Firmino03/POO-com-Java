public class Casting {
      public static void main(String[] args) {

        int numero = (int) 3.9;
        int letra = (int) 'K';

        System.out.println(numero);
        System.out.println(letra);

        // 3.9 convertido para int resulta em 3
        // 'K' convertido para int resulta em 75, que é o valor da tabela ASCII
    }
}
